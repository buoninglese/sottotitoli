#!/usr/bin/env bash
# Regenerate supabase/schema-live.sql — a readable, diffable snapshot of the
# LIVE database's schema.
#
# Why this exists
# ---------------
# Three production bugs were caused by constraints that exist ONLY in the live
# database and appear nowhere in supabase/migrations:
#
#   1. ai_report_requests.family_key NOT NULL            -> blocked every report
#   2. ai_report_requests_scope_type_check               -> blocked multi-session
#                                                            inserts after the
#                                                            credits were taken
#   3. session_ai_reports.session_id NOT NULL            -> blocked every
#                                                            profile-driven
#                                                            synthesis
#
# Each was invisible from the repository. Reading the migrations gave a picture
# of the schema that was simply wrong. This snapshot makes the live truth
# reviewable in a pull request.
#
# Why not `supabase db dump`?
# ---------------------------
# `supabase db dump --linked` needs the database password, which must never be
# pasted into an agent or a script. It reads the catalog over the Management API
# instead (same path as `supabase db query`), so it needs no password and can be
# run by anyone with CLI access. It is not a byte-exact pg_dump; it is a complete
# inventory of the parts that have actually bitten us — columns and their
# nullability, CHECK/UNIQUE/FK constraints, indexes, RLS policies, function
# security and grants.
#
# Usage:  ./scripts/dump-live-schema.sh
# Then:   git diff supabase/schema-live.sql

set -euo pipefail

cd "$(dirname "$0")/.."
OUT="supabase/schema-live.sql"
SQL="$(mktemp)"
trap 'rm -f "$SQL"' EXIT

cat > "$SQL" <<'SQL'
with parts as (

  select 1 as ord, 'HEADER' as section,
    '-- supabase/schema-live.sql' || E'\n'
    || '-- GENERATED by scripts/dump-live-schema.sh — do not edit by hand.' || E'\n'
    || '-- Live project: qzqmuegbpmvqrjrlfbgk' || E'\n'
    || '-- Generated: ' || to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') || E'\n'
    || '--' || E'\n'
    || '-- A snapshot of the LIVE schema, including constraints that exist only on' || E'\n'
    || '-- the server. Compare against supabase/migrations/ when something behaves' || E'\n'
    || '-- in a way the migrations do not explain.' || E'\n'
    as body

  -- ── Columns ──────────────────────────────────────────────────────────────
  union all
  select 2, 'COLUMNS',
    E'\n-- ═══ COLUMNS ═══\n'
    || coalesce(string_agg(
         '  ' || table_name || '.' || column_name || ' ' || data_type
         || case when is_nullable = 'NO' then ' NOT NULL' else '' end
         || case when column_default is not null then ' DEFAULT ' || column_default else '' end,
         E'\n' order by table_name, ordinal_position), '  (none)')
    || E'\n'
  from information_schema.columns
  where table_schema = 'public'

  -- ── CHECK constraints: the #1 source of invisible breakage ───────────────
  union all
  select 3, 'CHECKS',
    E'\n-- ═══ CHECK CONSTRAINTS (live-only ones live here) ═══\n'
    || coalesce((
         select string_agg('  ' || c.conrelid::regclass::text || '.' || c.conname
                           || '  ' || pg_get_constraintdef(c.oid),
                           E'\n' order by c.conrelid::regclass::text, c.conname)
         from pg_constraint c
         join pg_namespace n on n.oid = c.connamespace
         where n.nspname = 'public' and c.contype = 'c'), '  (none)')
    || E'\n'

  -- ── Primary keys and uniques ─────────────────────────────────────────────
  union all
  select 4, 'KEYS',
    E'\n-- ═══ PRIMARY KEYS / UNIQUE CONSTRAINTS ═══\n'
    || coalesce((
         select string_agg('  ' || c.conrelid::regclass::text || ' [' || c.contype::text || '] '
                           || pg_get_constraintdef(c.oid),
                           E'\n' order by c.conrelid::regclass::text, c.contype, c.conname)
         from pg_constraint c
         join pg_namespace n on n.oid = c.connamespace
         where n.nspname = 'public' and c.contype in ('p', 'u')), '  (none)')
    || E'\n'

  -- ── Foreign keys ─────────────────────────────────────────────────────────
  union all
  select 5, 'FKS',
    E'\n-- ═══ FOREIGN KEYS ═══\n'
    || coalesce((
         select string_agg('  ' || c.conrelid::regclass::text || ' ' || c.conname
                           || '  ' || pg_get_constraintdef(c.oid),
                           E'\n' order by c.conrelid::regclass::text, c.conname)
         from pg_constraint c
         join pg_namespace n on n.oid = c.connamespace
         where n.nspname = 'public' and c.contype = 'f'), '  (none)')
    || E'\n'

  -- ── Indexes not backing a constraint ─────────────────────────────────────
  union all
  select 6, 'INDEXES',
    E'\n-- ═══ INDEXES ═══\n'
    || coalesce((
         select string_agg('  ' || tablename || '  ' || indexdef,
                           E'\n' order by tablename, indexname)
         from pg_indexes
         where schemaname = 'public'
           and indexname not in (
             select conname from pg_constraint c
             join pg_namespace n on n.oid = c.connamespace
             where n.nspname = 'public')), '  (none)')
    || E'\n'

  -- ── Row Level Security: is it on, and what are the policies? ─────────────
  union all
  select 7, 'RLS',
    E'\n-- ═══ ROW LEVEL SECURITY ═══\n'
    || coalesce((
         select string_agg('  ' || c.relname || '  rls='
                           || case when c.relrowsecurity then 'ENABLED' else 'DISABLED' end
                           || case when c.relforcerowsecurity then ' FORCED' else '' end,
                           E'\n' order by c.relname)
         from pg_class c
         join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'public' and c.relkind = 'r'), '  (none)')
    || E'\n\n  --- policies ---\n'
    || coalesce((
         select string_agg('  ' || tablename || ' | ' || policyname || ' | cmd=' || cmd
                           || ' | roles=' || array_to_string(roles, ',')
                           || ' | using=' || coalesce(qual, '-')
                           || ' | check=' || coalesce(with_check, '-'),
                           E'\n' order by tablename, policyname)
         from pg_policies where schemaname = 'public'), '  (none)')
    || E'\n'

  -- ── Functions: SECURITY DEFINER + grants decide who can move money ───────
  union all
  select 8, 'FUNCS',
    E'\n-- ═══ FUNCTIONS ═══\n'
    || coalesce((
         select string_agg(
                  '  ' || p.proname || '(' || pg_get_function_arguments(p.oid) || ')'
                  || case when p.prosecdef then ' SECURITY DEFINER' else '' end
                  || '  volatility=' || p.provolatile::text
                  || '  execute=' || coalesce((
                       select string_agg(rp.grantee, ',' order by rp.grantee)
                       from information_schema.routine_privileges rp
                       where rp.specific_schema = 'public'
                         and rp.routine_name = p.proname), '-'),
                  E'\n' order by p.proname)
         from pg_proc p
         join pg_namespace n on n.oid = p.pronamespace
         where n.nspname = 'public'), '  (none)')
    || E'\n'

  -- ── Triggers ─────────────────────────────────────────────────────────────
  union all
  select 9, 'TRIGGERS',
    E'\n-- ═══ TRIGGERS ═══\n'
    || coalesce((
         select string_agg('  ' || t.tgrelid::regclass::text || ' | ' || t.tgname
                           || ' | ' || pg_get_triggerdef(t.oid),
                           E'\n' order by t.tgrelid::regclass::text, t.tgname)
         from pg_trigger t
         join pg_class c on c.oid = t.tgrelid
         join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'public' and not t.tgisinternal), '  (none)')
    || E'\n'

  -- ── Migrations recorded on the server vs. files in the repo ──────────────
  union all
  select 10, 'MIGRATIONS',
    E'\n-- ═══ MIGRATIONS RECORDED ON THE SERVER ═══\n'
    || coalesce((
         select string_agg('  ' || version || '  ' || coalesce(name, ''),
                           E'\n' order by version)
         from supabase_migrations.schema_migrations), '  (none)')
    || E'\n'
)
select string_agg(body, '' order by ord) as r from parts;
SQL

# `supabase db query` prints a status line before the JSON; locate the object.
supabase db query -f "$SQL" --linked 2>/dev/null \
  | python3 -c 'import json,sys
t = sys.stdin.read()
i = t.find("{")
if i < 0:
    sys.exit("no JSON in db query output")
obj, _ = json.JSONDecoder().raw_decode(t[i:])
sys.stdout.write(obj["rows"][0]["r"] if obj["rows"] else "")' > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
