#!/usr/bin/env python3
"""
build_tokens.py — tokens.json becomes CSS, and the build FAILS on bad contrast.
==============================================================================

One source of truth, two consumers:

    tokens.json ──► brand/tokens.css     (the page: custom properties, percentages)
                └─► brand/grid.py        (the renderer: the same numbers in pixels)

Before this, the video baked coordinates and the CSS repeated them by hand. That
survives exactly until someone nudges one of them, and then the painted hairlines
and the HTML sit a few pixels apart forever, with nothing to catch it.

The contrast gate is the other half. WCAG AA is a checklist item people tick by
eye; here it is arithmetic over the actual hex values in tokens.json, and a
failing pair stops the build. Text nobody can read is not a style choice.

    python brand/build_tokens.py
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_CSS = os.path.join(HERE, "tokens.css")
OUT_GRID = os.path.join(HERE, "grid.py")


# ── colour maths ──────────────────────────────────────────
def _srgb_to_lin(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def luminance(hex_str):
    h = hex_str.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return 0.2126 * _srgb_to_lin(r) + 0.7152 * _srgb_to_lin(g) + 0.0722 * _srgb_to_lin(b)


def contrast(a, b):
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


# ── derived grid ──────────────────────────────────────────
def derive(t):
    f, g = t["frame"], t["grid"]
    W, H = f["w"], f["h"]
    margin, header, gutter, phi = g["margin"], g["header_h"], g["gutter"], g["phi"]

    content_y = margin + header + gutter
    content_h = H - margin - content_y
    content_w = W - 2 * margin
    panel_w = round(content_w / phi)
    col_x = margin + panel_w + gutter
    col_w = W - margin - col_x
    col_a_h = round((content_h - gutter) / phi)
    tab_x0 = W - margin - (g["tabs"] * g["tab_w"] + (g["tabs"] - 1) * gutter)

    d = dict(W=W, H=H, margin=margin, header=header, gutter=gutter,
             content_y=content_y, content_h=content_h, content_w=content_w,
             panel_w=panel_w, col_x=col_x, col_w=col_w, col_a_h=col_a_h,
             col_b_h=content_h - col_a_h - gutter, tab_x0=tab_x0,
             logo_w=g["logo_w"], logo_cx=margin + 14 + g["logo_w"] // 2,
             logo_cy=margin + header // 2, tabs=g["tabs"], tab_w=g["tab_w"])
    # percentage forms — identical geometry at any canvas size
    d["pct"] = {
        "margin_x": margin / W * 100, "margin_y": margin / H * 100,
        "header_h": header / H * 100, "header_w": (W - 2 * margin) / W * 100,
        "content_y": content_y / H * 100, "content_h": content_h / H * 100,
        "panel_w": panel_w / W * 100, "col_x": col_x / W * 100,
        "col_w": col_w / W * 100, "col_a_h": col_a_h / H * 100,
        "col_b_y": (content_y + col_a_h + gutter) / H * 100,
        "col_b_h": (content_h - col_a_h - gutter) / H * 100,
        "tab_x": tab_x0 / W * 100, "tab_w": g["tab_w"] / W * 100,
        "tab_h": (header - 2 * g["tab_pad"]) / H * 100,
        "logo_cx": (margin + 14 + g["logo_w"] // 2) / W * 100,
        "logo_cy": (margin + header // 2) / H * 100,
        "logo_w": g["logo_w"] / W * 100,
        # the two columns as a fraction of the CONTENT width, which is the box
        # a page actually lays out in. This is the pair a CSS grid needs; the
        # frame-relative numbers above are for absolutely-positioned overlays.
        "panel_of_content": panel_w / content_w * 100,
        "col_of_content": col_w / content_w * 100,
    }
    return d


def main():
    t = json.load(open(os.path.join(HERE, "tokens.json")))
    G = derive(t)
    c, ty, fn = t["colour"], t["type"], t["font"]

    # ── contrast gate ─────────────────────────────────────
    print("CONTRAST GATE (WCAG 2.1 AA)")
    failed = []
    for kind, pairs in (("body", t["contrast_gate"]["required"]),
                        ("large-text", t["contrast_gate"]["large_only"])):
        for a, b, need in pairs:
            got = contrast(c[a], c[b])
            ok = got >= need
            print(f"  {kind:<10} {a:>6} on {b:<8} {got:5.2f}:1  need {need}  "
                  f"{'PASS' if ok else 'FAIL'}")
            if not ok:
                failed.append((kind, a, b, got, need))
    if failed:
        print(f"\nREFUSING to write CSS: {len(failed)} pair(s) below AA. "
              f"Raise the text colour, do not lower the gate.")
        return 1

    # ── css ───────────────────────────────────────────────
    p = G["pct"]
    lines = [
        "/* GENERATED by brand/build_tokens.py from brand/tokens.json.",
        "   Do not edit by hand: edit the JSON and re-run. */",
        ":root {",
        f"  --frame-w: {G['W']};",
        f"  --frame-h: {G['H']};",
        "",
        "  /* grid — percentages of the 1920x1080 frame, so the page and the",
        "     rendered video use literally the same numbers */",
        f"  --g-margin-x: {p['margin_x']:.4f}%;",
        f"  --g-margin-y: {p['margin_y']:.4f}%;",
        f"  --g-header-h: {p['header_h']:.4f}%;",
        f"  --g-header-w: {p['header_w']:.4f}%;",
        f"  --g-content-y: {p['content_y']:.4f}%;",
        f"  --g-content-h: {p['content_h']:.4f}%;",
        f"  --g-panel-w: {p['panel_w']:.4f}%;",
        f"  --g-col-x: {p['col_x']:.4f}%;",
        f"  --g-col-w: {p['col_w']:.4f}%;",
        f"  --g-box-a-h: {p['col_a_h']:.4f}%;",
        f"  --g-box-b-y: {p['col_b_y']:.4f}%;",
        f"  --g-box-b-h: {p['col_b_h']:.4f}%;",
        f"  --g-tab-x: {p['tab_x']:.4f}%;",
        f"  --g-tab-w: {p['tab_w']:.4f}%;",
        f"  --g-tab-h: {p['tab_h']:.4f}%;",
        "",
        "  /* the same grid in px — a percentage is only meaningful inside a",
        "     positioned box of known size, so page padding needs the real",
        "     number. One source, two forms. */",
        f"  --g-margin-px: {G['margin']}px;",
        f"  --g-header-px: {G['header']}px;",
        f"  --g-gutter-px: {G['gutter']}px;",
        f"  --g-content-y-px: {G['content_y']}px;",
        f"  --g-panel-px: {G['panel_w']}px;",
        f"  --g-col-px: {G['col_w']}px;",
        "",
        "  /* the golden split as a share of the content box — this is what a",
        "     grid track wants. 61.83 / 37.04 with a 21px gutter, not 1fr / 33% */",
        f"  --g-panel-of-content: {p['panel_of_content']:.4f}%;",
        f"  --g-col-of-content: {p['col_of_content']:.4f}%;",
        "",
        "  /* type */",
        f"  --font-display: {fn['display']};",
        f"  --font-ui: {fn['ui']};",
        f"  --font-mono: {fn['mono']};",
        f"  --t-display: clamp(34px, 4.4vw, {ty['display']}px);",
        f"  --t-h1: clamp(26px, 2.9vw, {ty['h1']}px);",
        f"  --t-h2: {ty['h2']}px;",
        f"  --t-lede: clamp(16px, 1.35vw, {ty['lede']}px);",
        f"  --t-body: {ty['body']}px;",
        f"  --t-small: {ty['small']}px;",
        f"  --t-micro: {ty['micro']}px;",
        f"  --lh-tight: {ty['lh_tight']};",
        f"  --lh-body: {ty['lh_body']};",
        f"  --tr-display: {ty['tracking_display']}em;",
        f"  --tr-caps: {ty['tracking_caps']}em;",
        f"  --tr-caps-wide: {ty['tracking_caps_wide']}em;",
        "",
        "  /* colour */",
    ]
    for k, v in c.items():
        lines.append(f"  --c-{k}: {v};")
    lines += [
        "",
        "  /* fixed z-index scale — no arbitrary z-* */",
        "  --z-bg: 0; --z-content: 1; --z-chrome: 2; --z-skip: 3;",
        "}",
        "",
    ]
    open(OUT_CSS, "w").write("\n".join(lines))
    print(f"\nwrote {OUT_CSS}")

    # ── python constants for the renderer ─────────────────
    open(OUT_GRID, "w").write(
        '"""GENERATED from tokens.json. Do not edit."""\n\n'
        + "\n".join(f"{k} = {v!r}" for k, v in G.items() if k != "pct")
        + "\n\nPCT = " + repr(G["pct"]) + "\n")
    print(f"wrote {OUT_GRID}")
    print(f"\ngrid: margin {G['margin']}  header {G['header']}  gutter {G['gutter']}  "
          f"panel {G['panel_w']}w  col {G['col_w']}w")
    return 0


if __name__ == "__main__":
    sys.exit(main())
